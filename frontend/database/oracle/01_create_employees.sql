CREATE TABLE NHAN_VIEN (
    MA_NV NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MA_NHAN_VIEN VARCHAR2(20 CHAR) NOT NULL,
    HO_TEN VARCHAR2(100 CHAR) NOT NULL,
    GIOI_TINH VARCHAR2(10 CHAR),
    NGAY_SINH DATE,
    PHONG_BAN VARCHAR2(100 CHAR),
    CHUC_VU VARCHAR2(100 CHAR),
    LUONG NUMBER(12, 2) DEFAULT 0 NOT NULL,
    EMAIL VARCHAR2(255 CHAR),
    SO_DIEN_THOAI VARCHAR2(20 CHAR),
    NGAY_TAO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    NGAY_CAP_NHAT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_NHAN_VIEN PRIMARY KEY (MA_NV),
    CONSTRAINT UK_NHAN_VIEN_MA UNIQUE (MA_NHAN_VIEN),
    CONSTRAINT CK_NHAN_VIEN_LUONG CHECK (LUONG >= 0)
);

